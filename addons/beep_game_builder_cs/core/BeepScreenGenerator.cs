";

        // ── name helpers ──

        /// <summary>"race results" / "race_results" / "RaceResults" → "RaceResults".</summary>
        private static string ToPascal(string raw)
        {
            var sb = new System.Text.StringBuilder();
            bool up = true;
            foreach (char ch in raw)
            {
                if (char.IsLetterOrDigit(ch)) { sb.Append(up ? char.ToUpperInvariant(ch) : ch); up = false; }
                else up = true;
            }
            return sb.ToString();
        }

        /// <summary>"RaceResults" → "race_results".</summary>
        private static string ToSnake(string pascal)
        {
            var sb = new System.Text.StringBuilder();
            for (int i = 0; i < pascal.Length; i++)
            {
                if (i > 0 && char.IsUpper(pascal[i])) sb.Append('_');
                sb.Append(char.ToLowerInvariant(pascal[i]));
            }
            return sb.ToString();
        }

        /// <summary>"RaceResults" → "Race Results", for a default screen title.</summary>
        private static string Humanise(string pascal)
        {
            var sb = new System.Text.StringBuilder();
            for (int i = 0; i < pascal.Length; i++)
            {
                if (i > 0 && char.IsUpper(pascal[i])) sb.Append(' ');
                sb.Append(pascal[i]);
            }
            return sb.ToString();
        }
    }
}
