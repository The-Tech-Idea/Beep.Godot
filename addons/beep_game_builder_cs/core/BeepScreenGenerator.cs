using Godot;
using System.Collections.Generic;

namespace Beep.GameBuilder
{
    /// <summary>
    /// Stamps a new genre screen that already obeys every convention this repo enforces,
    /// instead of leaving them to be rediscovered (and reviewed) each time:
    ///
    ///  • an OPAQUE ColorRect named "Background", so ThemePresetComponent paints it from bg_canvas;
    ///  • a header whose title carries <c>theme_type_variation = &amp;"BeepTitle"</c>, an accent rule,
    ///    and a back button with a real height (120×44 — a 0-height button was the shipped default);
    ///  • ThemePresetComponent parented to the CONTENT Control with the right GenreName;
    ///  • GameInfoBinder bound to the title;
    ///  • PascalCase [Export] names, which Godot silently drops when written snake_case;
    ///  • a C# script resolving its button with <c>ConnectButton("BackButton", …)</c> — by NAME, so a
    ///    later restyle that inserts a wrapper cannot kill it.
    ///
    /// EDITOR ONLY: writes into res://.
    /// </summary>
    public static class BeepScreenGenerator
    {
        /// <summary>Create <c>res://scenes/ui/&lt;genre&gt;/&lt;snake_name&gt;.tscn</c> and its script.
        /// Returns a log; nothing is overwritten unless <paramref name="overwrite"/> is set.</summary>
        public static List<string> CreateScreen(string genreId, string screenName, string title, bool overwrite = false)
        {
            var log = new List<string>();
            if (string.IsNullOrWhiteSpace(screenName)) { log.Add("✗ screen name is required"); return log; }

            string cls = ToPascal(screenName);
            string snake = ToSnake(cls);
            if (string.IsNullOrEmpty(cls)) { log.Add($"✗ '{screenName}' has no usable letters for a class name"); return log; }
            if (string.IsNullOrWhiteSpace(title)) title = Humanise(cls);

            string scriptDir = $"res://scripts/screens/{genreId}";
            string sceneDir = $"res://scenes/ui/{genreId}";
            BeepFileUtils.EnsureDir(scriptDir);
            BeepFileUtils.EnsureDir(sceneDir);

            string scriptPath = $"{scriptDir}/{cls}.cs";
            string scenePath = $"{sceneDir}/{snake}.tscn";

            if (BeepFileUtils.SafeWriteText(scriptPath, ScriptSource(cls), overwrite)) log.Add($"✓ {scriptPath}");
            else log.Add($"· {scriptPath} exists — kept");

            if (BeepFileUtils.SafeWriteText(scenePath, SceneSource(cls, snake, title, genreId, scriptPath), overwrite)) log.Add($"✓ {scenePath}");
            else log.Add($"· {scenePath} exists — kept");

            log.Add("→ Build the project so Godot registers the new script, then open the scene.");
            return log;
        }

        private static string ScriptSource(string cls) =>
$@"using Godot;
using Beep.ECS;
using Beep.ECS.Scenes;

/// <summary>Generated by Beep. Wire this screen's own controls here.</summary>
[Tool]
[GlobalClass]
public partial class {cls} : Control
{{
    public override void _Ready()
    {{
        if (Engine.IsEditorHint()) return;

        // Resolve by NAME, never by path: a path bakes in the layout, so inserting one wrapper
        // container later silently kills every button under it.
        this.ConnectButton(""BackButton"", () => UI.SceneNav.CloseOrReturn(this, GameApp.Instance?.GameScenePath));
    }}
}}
";

        private static string SceneSource(string cls, string snake, string title, string genreId, string scriptPath) =>
$@"[gd_scene load_steps=3 format=3]

[ext_resource type=""Script"" path=""res://addons/beep_game_builder_cs/ecs/ui/ThemePresetComponent.cs"" id=""1_theme""]
[ext_resource type=""Script"" path=""res://addons/beep_game_builder_cs/ecs/ui/GameInfoBinder.cs"" id=""2_binder""]
[ext_resource type=""Script"" path=""{scriptPath}"" id=""3_script""]

[node name=""{cls}"" type=""Control""]
anchors_preset = 15
anchor_right = 1.0
anchor_bottom = 1.0
grow_horizontal = 2
grow_vertical = 2
